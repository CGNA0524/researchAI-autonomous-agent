"""
Application Configuration and Settings Management.
Reads settings from environment variables and .env files with sensible defaults.
"""

from functools import lru_cache
from typing import List
from pydantic_settings import BaseSettings, SettingsConfigDict
from pydantic import Field


class Settings(BaseSettings):
    """Global configuration settings for the AI Research Agent."""

    # Application Environment
    APP_ENV: str = Field(default="development", description="Environment: development, staging, production")
    LOG_LEVEL: str = Field(default="INFO", description="Logging level: DEBUG, INFO, WARNING, ERROR")
    HOST: str = Field(default="0.0.0.0", description="Host address for FastAPI server")
    PORT: int = Field(default=8000, description="Port for FastAPI server")

    # LLM Provider Selection
    LLM_PROVIDER: str = Field(
        default="groq",
        description="Active LLM provider: 'groq' or 'openai'"
    )

    # Groq API Configuration
    GROQ_API_KEY: str = Field(
        default="",
        description="Groq API key for LLM inference (console.groq.com)"
    )
    GROQ_MODEL: str = Field(
        default="llama-3.3-70b-versatile",
        description="Primary Groq model supporting tool-calling and structured outputs"
    )
    GROQ_FALLBACK_MODEL: str = Field(
        default="llama-3.1-8b-instant",
        description="Fallback Groq model if primary model experiences rate limits"
    )
    GROQ_TEMPERATURE: float = Field(
        default=0.1,
        ge=0.0,
        le=2.0,
        description="Sampling temperature; low for factual, reproducible synthesis"
    )
    GROQ_MAX_TOKENS: int = Field(
        default=4096,
        description="Maximum tokens generated by the LLM in a single completion"
    )

    # OpenAI API Configuration
    OPENAI_API_KEY: str = Field(
        default="",
        description="OpenAI API key for LLM inference (platform.openai.com)"
    )
    OPENAI_MODEL: str = Field(
        default="gpt-4o-mini",
        description="Configurable OpenAI model (e.g. gpt-4o-mini, gpt-4o)"
    )
    OPENAI_TEMPERATURE: float = Field(
        default=0.1,
        ge=0.0,
        le=2.0,
        description="Sampling temperature for OpenAI inference"
    )
    OPENAI_MAX_TOKENS: int = Field(
        default=4096,
        description="Maximum tokens generated by OpenAI in a single completion"
    )
    MAX_REQUEST_BUDGET_USD: float = Field(
        default=0.10,
        description="Safety threshold: max estimated USD budget per research request to protect API credits"
    )

    # Search & Extraction Settings
    MAX_SEARCH_RESULTS: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Maximum number of search results retrieved per query"
    )
    MAX_EXTRACT_PAGES: int = Field(
        default=3,
        ge=1,
        le=10,
        description="Maximum full web pages to extract during a single research task"
    )
    HTTP_TIMEOUT_SECONDS: float = Field(
        default=10.0,
        ge=1.0,
        le=60.0,
        description="HTTP request timeout in seconds for web search and page scrapers"
    )
    MAX_PAGE_CHARS: int = Field(
        default=6000,
        ge=500,
        le=30000,
        description="Maximum readable text characters extracted per webpage"
    )

    # Reliability and Retries
    MAX_RETRIES: int = Field(default=3, description="Maximum retry attempts for transient API failures")
    BACKOFF_FACTOR: float = Field(default=1.5, description="Exponential backoff factor for retries")

    # Security: SSRF Denylist
    BLOCKED_HOSTS: List[str] = Field(
        default_factory=lambda: [
            "localhost",
            "127.0.0.1",
            "0.0.0.0",
            "::1",
            "169.254.169.254",  # AWS/GCP metadata endpoint
            "metadata.google.internal",
        ],
        description="Hosts blocked to protect against Server-Side Request Forgery"
    )

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=True,
        extra="ignore"
    )


@lru_cache()
def get_settings() -> Settings:
    """Returns a cached singleton instance of application settings."""
    return Settings()


# Official model pricing in USD per 1,000,000 tokens (input, output)
# Reference: https://openai.com/api/pricing/
MODEL_PRICING_PER_1M: dict[str, dict[str, float]] = {
    "gpt-4o-mini": {"input": 0.150, "output": 0.600},
    "gpt-4o-mini-2024-07-18": {"input": 0.150, "output": 0.600},
    "gpt-4o": {"input": 2.50, "output": 10.00},
    "gpt-4o-2024-08-06": {"input": 2.50, "output": 10.00},
    "gpt-4o-2024-05-13": {"input": 5.00, "output": 15.00},
    "gpt-4-turbo": {"input": 10.00, "output": 30.00},
    "gpt-3.5-turbo": {"input": 0.50, "output": 1.50},
    "o1-mini": {"input": 3.00, "output": 12.00},
    "o1-preview": {"input": 15.00, "output": 60.00},
}


def get_model_pricing(model_name: str) -> dict[str, float] | None:
    """
    Returns the token pricing dictionary for a given model, or None if pricing is unconfigured.
    Rule: Never invent zero pricing for unknown models; return None to show cost as unavailable.
    """
    if not model_name:
        return None
    # Normalize model name for exact and prefix matches
    clean_name = model_name.strip().lower()
    if clean_name in MODEL_PRICING_PER_1M:
        return MODEL_PRICING_PER_1M[clean_name]
    # Check without date suffix
    for known_model, pricing in MODEL_PRICING_PER_1M.items():
        if clean_name.startswith(known_model):
            return pricing
    return None

