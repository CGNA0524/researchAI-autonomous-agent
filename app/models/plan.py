"""
Internal planning and orchestration data models.
"""

from typing import List, Optional, Any, Dict
from pydantic import BaseModel, Field


class ResearchTask(BaseModel):
    """Sub-task decomposed from the primary user research question."""
    task_id: int = Field(..., description="Unique sequential identifier for this task")
    objective: str = Field(..., description="Specific objective for this sub-task")
    search_queries: List[str] = Field(
        default_factory=list,
        description="Search engine queries designed to retrieve answers for this sub-task"
    )
    aspects_to_investigate: List[str] = Field(
        default_factory=list,
        description="Key technical or factual dimensions to check"
    )


class ResearchPlan(BaseModel):
    """Structured plan generated by the Research Planner component."""
    original_question: str
    primary_objective: str
    needs_web_search: bool = True
    target_entities: List[str] = Field(
        default_factory=list,
        description="Target entities, products, frameworks, or subjects of research"
    )
    evaluation_dimensions: List[str] = Field(
        default_factory=list,
        description="Explicit evaluation or analysis dimensions requested"
    )
    tasks: List[ResearchTask] = Field(default_factory=list)
    initial_rationale: str = ""


class ToolExecutionRecord(BaseModel):
    """Log record representing an individual tool execution."""
    tool_name: str
    arguments: Dict[str, Any] = Field(default_factory=dict)
    success: bool
    result_summary: str = ""
    duration_ms: float = 0.0
    error_message: Optional[str] = None
